    /// <summary>按版本号查找（同时接受 "1.14" 与 "v1.14"）。</summary>
    public static ReleaseNote? Find(string? version)
    {
        if (string.IsNullOrWhiteSpace(version)) return null;
        var v = version.Trim().TrimStart('v', 'V');
        return Array.Find(All, r => r.Version == v);
    }

    /// <summary>取前 N 条（N ≤ 0 时返回全部）。</summary>
    public static ReleaseNote[] Take(int count)
        => count > 0 && count < All.Length ? All[..count] : All;
