namespace KidsSafeDesktop.Models;

/// <summary>一个睡前故事。正文按段存储，朗读时逐段播放并高亮。</summary>
public class BedtimeStory
{
    public string Id { get; init; } = string.Empty;
    public string Emoji { get; init; } = "📖";
    public string Title { get; init; } = string.Empty;
    public string Category { get; init; } = "童话";
    public string Summary { get; init; } = string.Empty;
    /// <summary>故事最后想留给孩子的一句话。</summary>
    public string Moral { get; init; } = string.Empty;
    public string[] Paragraphs { get; init; } = Array.Empty<string>();

    public string TagText => $"🌙 {Category} · {Paragraphs.Length} 段";
    public string MinutesText => $"约 {Math.Max(1, Paragraphs.Sum(p => p.Length) / 180)} 分钟";
    public string FullText => string.Join("\n", Paragraphs);
}

