using Microsoft.Maui.Graphics;

namespace KidsSafeDesktop.Models;

/// <summary>家长可以做的事（每条含「具体动作」与「为什么有效」）。</summary>
public class ParentDoTip
{
    public string Emoji { get; init; } = "✅";
    public string Title { get; init; } = "";
    public string Detail { get; init; } = "";
    public string Why { get; init; } = "";
}

/// <summary>
/// 家长不该做的事。这是本页的重点：
/// 每条都写清「为什么有害（机制）」与「换成怎么做」，
/// 因为只说「不要这样」家长做不到，给了替代动作才做得到。
/// </summary>
public class ParentAvoidTip
{
    public string Emoji { get; init; } = "⛔";
    public string Bad { get; init; } = "";
    public string Why { get; init; } = "";
    public string Better { get; init; } = "";
}

/// <summary>一句话的前后对比（说错了 vs 换一种说法）。</summary>
public class PhraseSwap
{
    public string Bad { get; init; } = "";
    public string Good { get; init; } = "";
    public string Why { get; init; } = "";
}

/// <summary>需要就医 / 找专业人士的信号。</summary>
public class WarningSign
{
    public string Text { get; init; } = "";
    public bool Urgent { get; init; }

    /// <summary>红色 = 需要立刻处理；黄色 = 需要尽快预约评估。</summary>
    public string Dot => Urgent ? "🔴" : "🟡";

    public Color TextColor => Urgent ? Color.FromArgb("#B71C1C") : Color.FromArgb("#4E342E");
}

