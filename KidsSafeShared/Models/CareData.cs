using Microsoft.Maui.Graphics;

namespace KidsSafeDesktop.Models;

/// <summary>八种基础心情。刻意不做「好 / 坏」二分：难过和生气也是需要被看见的情绪。</summary>
public class MoodKind
{
    public string Id { get; init; } = string.Empty;
    public string Emoji { get; init; } = "🙂";
    public string Label { get; init; } = string.Empty;
    /// <summary>孩子能听懂的一句解释。</summary>
    public string Hint { get; init; } = string.Empty;
    public string Hex { get; init; } = "#FFD54F";

    public Color Color => Color.FromArgb(Hex);
}

/// <summary>一天的心情记录。每天只保留一条（再记录会覆盖）。</summary>
public class MoodEntry
{
    public string Date { get; set; } = string.Empty;     // yyyy-MM-dd
    public string MoodId { get; set; } = string.Empty;
    public string Note { get; set; } = string.Empty;
    public string Time { get; set; } = string.Empty;

    public MoodKind Mood => CareCatalog.MoodOf(MoodId);
}

/// <summary>心理小课堂的一节（孩子版 / 家长版共用结构）。</summary>
public class CareLesson
{
    public string Id { get; init; } = string.Empty;
    public string Emoji { get; init; } = "💗";
    public string Title { get; init; } = string.Empty;
    public string Subtitle { get; init; } = string.Empty;
    /// <summary>kids / parents。</summary>
    public string Audience { get; init; } = "kids";
    public string Tag { get; init; } = string.Empty;
    public int Minutes { get; init; } = 3;
    public string KeyLine { get; init; } = string.Empty;
    public (string Heading, string Body)[] Sections { get; init; } = Array.Empty<(string, string)>();

    public bool ForParents => Audience == "parents";
    public string MetaText => $"{Tag} · 约 {Minutes} 分钟";
    public string AudienceText => ForParents ? "给家长" : "给孩子";
}

/// <summary>求助渠道。</summary>
public class HelpChannel
{
    public string Emoji { get; init; } = "📞";
    public string Name { get; init; } = string.Empty;
    public string Number { get; init; } = string.Empty;
    public string When { get; init; } = string.Empty;
    public bool Urgent { get; init; }
}

